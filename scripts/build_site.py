"""Builds assets/content.js: every example, already run, with its output.

Usage (from project root):  python3 scripts/build_site.py
Run it again whenever you edit anything in src/data/.
Stops with an error if any example fails.
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import pandas as pd
from pygments import highlight
from pygments.formatters import HtmlFormatter
from pygments.lexers import PythonLexer

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
CHART_DIR = ROOT / "assets" / "charts"
OUT_FILE = ROOT / "assets" / "content.js"

sys.path.insert(0, str(Path(__file__).resolve().parent))
import runner  # noqa: E402


def load_content():
    raw = subprocess.check_output(["node", "scripts/dump_content.mjs"], cwd=ROOT)
    return json.loads(raw)


def highlight_python(code):
    return highlight(code, PythonLexer(), HtmlFormatter(nowrap=True))


def save_charts(images, name):
    paths = []
    for i, png_base64 in enumerate(images):
        file_name = f"{name}.png" if i == 0 else f"{name}-{i + 1}.png"
        import base64
        (CHART_DIR / file_name).write_bytes(base64.b64decode(png_base64))
        paths.append(f"assets/charts/{file_name}")
    return paths


def run_example(fn, name):
    result = json.loads(runner.run_cell(fn["code"]))
    if result["error"] or "Warning" in result["stdout"]:
        raise SystemExit(f"Example {name} failed:\n{result['error'] or result['stdout']}")
    return {
        "text": "\n".join(part for part in (result["stdout"], result["value"]) if part).rstrip(),
        "table": result["table"],
        "charts": save_charts(result["images"], name),
    }


def dataset_previews():
    sales = pd.read_csv(DATA_DIR / "sales.csv")
    messy = pd.read_csv(DATA_DIR / "messy.csv")
    return {
        "sales": sales.head(6).to_html(border=0, classes="df-table", index=False),
        "messy": messy.to_html(border=0, classes="df-table", index=False, na_rep="NaN"),
    }


def main():
    content = load_content()
    shutil.rmtree(CHART_DIR, ignore_errors=True)
    CHART_DIR.mkdir(parents=True)

    work_dir = tempfile.mkdtemp()
    for item in DATA_DIR.iterdir():
        shutil.copy(item, work_dir)
    os.chdir(work_dir)

    for category in content["categories"]:
        for fn in category["functions"]:
            name = f"{category['id']}-{fn['id']}"
            fn["output"] = run_example(fn, name)
            fn["codeHtml"] = highlight_python(fn["code"])
            print(f"ok  {name}")

    for item in content["qa"]:
        item["codeHtml"] = highlight_python(item["code"])

    content["previews"] = dataset_previews()
    OUT_FILE.write_text("// Generated by scripts/build_site.py. Do not edit by hand.\n"
                        f"window.GUIDE = {json.dumps(content, ensure_ascii=False)};\n")
    total = sum(len(c["functions"]) for c in content["categories"])
    print(f"\nBuilt {total} functions into {OUT_FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
